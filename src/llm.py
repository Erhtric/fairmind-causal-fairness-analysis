# Pydantic model used to define the JSON schema required by the API to enforce the structured output
class FairnessReport(BaseModel):
    """Both text and latex agree on the content"""

    text: str = Field(description="Plain text report.")
    latex: str = Field(description="Standalone LaTeX document.")


# Data container for the LLM report result, including text, LaTeX, and usage information
@dataclass(frozen=True)
class LLMReportResult:
    """
    LLM report result

    Args:
        text: The plain text report generated by the LLM.
        latex: The LaTeX report generated by the LLM.
        usage: The usage information returned by the LLM API (if any).
    """

    model: str
    effort: str
    text: str
    latex: str
    usage: Any = None

    def __iter__(self):
        return iter((self.text, self.latex, self.usage))


