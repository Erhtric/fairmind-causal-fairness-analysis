def load_prompt(name: str) -> str:
    """
    Load a prompt from the prompts directory.

    Args:
        name: The name of the prompt file to load.

    Returns:
        The contents of the prompt file as a string.
    """
    return (PROMPTS_DIR / name).read_text(encoding="utf-8")


def prepare_llm_payload_general(
    *,
    dataset_name: str,
    X: str,
    Y: str,
    W: Sequence[str] | None = None,
    Z: Sequence[str] | None = None,
    x0: Any = None,
    x1: Any = None,
    y_target: Any = None,
    results: dict[str, Any] | list[dict[str, Any]] | None = None,
    stepwise_results: Sequence[dict[str, Any]] | None = None,
    variable_metadata: dict[str, Any] | None = None,
    cont_results: Sequence[dict[str, Any]] | None = None,
    state_names: dict[str, Any] | None = None,
    graph_edges: Sequence[tuple[str, str]] | None = None,
    checks: dict[str, Any] | None = None,
    notes: Sequence[str] | None = None,
    ie_decomp: dict[str, Any] | None = None,
    se_decomp: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """
    Prepare a payload for LLM summarization.

    Args:
        dataset_name: Name of the dataset.
        X: Protected variable.
        Y: Outcome variable.
        W: Mediator variables.
        Z: Spurious features.
        x0: Value of X for the reference group.
        x1: Value of X for the target group.
        y_target: Value of Y for the target outcome.
        results: General results of the analysis.
        stepwise_results: Stepwise results of the analysis.
        variable_metadata: Metadata about the variables.
        cont_results: Continuous results of the analysis.
        state_names: Names of the states for categorical variables.
        graph_edges: Edges of the causal graph.
        checks: Checks performed during the analysis.
        notes: Additional notes or comments.
        ie_decomp: Individual effect decomposition results.
        se_decomp: Spurious effect decomposition results.

    Returns:
        A dictionary representing the payload for LLM summarization.
    """
    W = list(W or [])
    Z = list(Z or [])
    variable_metadata = dict(variable_metadata or {})
    checks = dict(checks or {})
    stepwise_results = list(stepwise_results or [])
    cont_results = list(cont_results or [])
    ie_decomp = dict(ie_decomp or {})
    se_decomp = dict(se_decomp or {})

    if isinstance(results, pd.Series):
        results = results.to_dict()
    elif isinstance(results, pd.DataFrame):
        results = results.to_dict(orient="records")

    if isinstance(variable_metadata, pd.Series):
        variable_metadata = variable_metadata.to_dict()

    if isinstance(state_names, pd.Series):
        state_names = state_names.to_dict()

    payload: dict[str, Any] = {
        "dataset": dataset_name,
        "causal_query": {
            "X": X,
            "Y": Y,
            "W": W,
            "Z": Z,
            "x0": x0,
            "x1": x1,
            "y_target": y_target,
        },
        "variable_metadata": variable_metadata,
        "state_names": state_names,
        "graph_edges": list(graph_edges) if graph_edges is not None else None,
        "results": results,
        "continuous_results": cont_results,
        "ie_decomp": ie_decomp,
        "se_decomp": se_decomp,
        "checks": checks,
        "notes": list(notes) if notes is not None else None,
    }

    if stepwise_results:
        payload["stepwise_results"] = stepwise_results

    return payload


def payload_to_json(payload: dict[str, Any], indent: int = 2) -> str:
    """Convert the payload dictionary to a JSON-formatted string with indentation."""
    return json.dumps(payload, indent=indent, ensure_ascii=False, default=str)


def _validate_prompt_kwargs(kwargs: dict[str, Any]) -> None:
    """
    Validate that the prompt_kwargs contain the necessary keys for the LLM-only pipeline.
    """
    required_keys = ["exposure", "outcome", "x0", "x1", "yt"]
    missing_keys = [key for key in required_keys if key not in kwargs]

    if missing_keys:
        raise ValueError(
            f"Missing required prompt keyword arguments for fairness analysis: {', '.join(missing_keys)}"
        )


def _format_variable_roles(names: Sequence[Any], values: Sequence[Any] | None) -> str:
    """Format a list of variable names, with their relevant levels if given."""
    if not names:
        return "None"
    formatted = ", ".join(str(name) for name in names)
    if values:
        formatted += f" (relevant levels: {', '.join(str(v) for v in values)})"
    return formatted


