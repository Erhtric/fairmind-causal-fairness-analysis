def summarize_fairmind(
    results: dict[str, Any],
    client: Any,
    model: str,
    prompt_path: str,
    effort: str = "high",
) -> LLMReportResult:
    """
    Summarize the fairness decomposition results using the LLM.

    Args:
        results: The fairness decomposition results to summarize.
        client: The LLM client to use for summarization.
        model: The LLM model to use for summarization.
        prompt_path: The path to the prompt file to use for summarization.
        effort: The reasoning effort level ("low", "medium", or "high").

    Returns:
        An LLMReportResult containing the summarized text, LaTeX, and usage information.
    """
    system_prompt = load_prompt(prompt_path)

    if "stepwise_results" in results:
        system_prompt += "\n\nInclude a 'Stepwise Effects Across Ordered Levels of X' section detailing the stepwise effects."

    user_prompt = (
        "Here are the fairness decomposition results in JSON:\n\n"
        + payload_to_json(results)
    )

    resp = client.responses.parse(
        model=model,
        reasoning={"effort": effort},
        instructions=system_prompt,
        text_format=FairnessReport,
        input=[
            {
                "role": "user",
                "content": [{"type": "input_text", "text": user_prompt}],
            }
        ],
    )

    return LLMReportResult(
        model=model,
        effort=effort,
        text=resp.output_parsed.text,
        latex=resp.output_parsed.latex,
        usage=resp.usage,
    )


### LLM-ONLY FAIRNESS DECOMPOSITION PROMPTING


def prepare_prompts(
    exposure: str,
    outcome: str,
    x0: Any,
    x1: Any,
    yt: Any,
    mediators: Sequence[str] | None = None,
    confounders: Sequence[str] | None = None,
    dataset_semantic_schema: dict[str, dict[str, Any]] | None = None,
    prompt_path: str = "only_llm_v2.txt",
) -> tuple[str, str]:
    """
    Build the prompts for the LLM-only fairness decomposition using a semantic schema.

    Expected format for dataset_semantic_schema:
    {
        "CREDIT_HISTORY": {
            "description": "The applicant's credit score.",
            "states": {0: "bad", 1: "good"}
        }
    }
    """
    mediators = list(mediators or [])
    confounders = list(confounders or [])
    schema = dataset_semantic_schema or {}

    def _format_feature(feature: str) -> str:
        info = schema.get(feature, {})
        desc = info.get("description", "")
        mapping = info.get("states", {})

        base_str = f"{feature}"
        if desc:
            base_str += f": {desc}"
        if mapping:
            map_str = ", ".join([f"{k} -> '{v}'" for k, v in mapping.items()])
            base_str += f" [States: {map_str}]"

        return base_str

    # Safe retrieval of specific state labels
    def _get_label(feature: str, val: Any) -> str:
        return schema.get(feature, {}).get("states", {}).get(val, str(val))

    system_prompt = load_prompt(prompt_path)

    z_formatted = (
        "\n  - ".join([_format_feature(z) for z in confounders])
        if confounders
        else "None"
    )
    w_formatted = (
        "\n  - ".join([_format_feature(w) for w in mediators]) if mediators else "None"
    )

    user_prompt = f"""
You are given a dataset file (a tabular dataset, e.g. CSV or plain-text table). Load it with the code interpreter and inspect the columns before computing anything.

Column roles and semantic schema:

- X (Exposure / Protected Attribute):
  - {_format_feature(exposure)}
  - Baseline (x0): {x0} ({_get_label(exposure, x0)})
  - Modified (x1): {x1} ({_get_label(exposure, x1)})

- Y (Outcome Attribute):
  - {_format_feature(outcome)}
  - Target (yt): {yt} ({_get_label(outcome, yt)})

- Z (Confounders / Spurious Features):
  - {z_formatted}

- W (Mediators):
  - {w_formatted}

Your task:
1. Load and inspect the dataset.
2. Compute the fairness decomposition according to Plečko and Bareinboim theory, isolating both general and variable-specific causal effects.
3. Interpret the numerical results using the provided semantic mappings.
4. Produce a structured report detailing the discriminatory pathways.
"""
    return system_prompt, user_prompt


def prepare_llm_only_prompts(
    x: Any = None,
    y: Any = None,
    x0: Any = None,
    x1: Any = None,
    y_value: Any = None,
    z: Sequence[Any] | None = None,
    w: Sequence[Any] | None = None,
    w_values: Sequence[Any] | None = None,
    z_values: Sequence[Any] | None = None,
    prompt_path: str = "only_llm_v2.txt",
) -> tuple[str, str]:
    """
    Build the prompts for the LLM-only fairness decomposition. The dataset
    itself is passed out-of-band (code-interpreter file); the prompts only
    carry the column roles.

    Args:
        x: The protected variable.
        y: The outcome variable.
        x0: The value of the protected variable for the first group.
        x1: The value of the protected variable for the second group.
        y_value: The value of the outcome variable.
        z: The spurious features.
        w: The mediator variables.
        w_values: The relevant levels of the mediator variables.
        z_values: The relevant levels of the spurious features.

    Returns:
        A tuple containing the system prompt and user prompt.
    """
    missing = [
        name
        for name, val in [
            ("x", x),
            ("y", y),
            ("x0", x0),
            ("x1", x1),
            ("y_value", y_value),
        ]
        if val is None
    ]
    if missing:
        raise ValueError(f"Missing required column roles: {', '.join(missing)}")

    z = list(z or [])
    w = list(w or [])

    system_prompt = load_prompt(prompt_path)

    user_prompt = f"""
You are given a dataset file (a tabular dataset, e.g. CSV or plain-text table). Load it with the code interpreter and inspect the columns before computing anything.

Column roles:
- X (protected variable): {x}, comparing x0={x0} vs x1={x1}
- Y (outcome attribute): {y}, outcome value of interest y={y_value}
- Z (spurious features / confounders): {_format_variable_roles(z, z_values)}
- W (mediator variables): {_format_variable_roles(w, w_values)}

Your task:
1. Load and inspect the dataset.
2. Compute the fairness decomposition according to Plecko and Bareinboim theory, both general and X-Z specific effects.
3. Produce a structured report.
"""
    return system_prompt, user_prompt


def generate_report_from_file_id(
    file_id: str,
    client: Any,
    model: str = "gpt-5.4-nano",
    prompt_kwargs: dict[str, Any] | None = None,
    effort: str = "high",
) -> LLMReportResult:
    """
    Generate a fairness decomposition report using the LLM, given a file ID.

    The dataset is made available to the model through the code-interpreter
    tool; only the column roles (from ``prompt_kwargs``) travel in the prompt.

    Args:
        file_id: The ID of the uploaded file containing the dataset.
        client: The LLM client to use for generation.
        model: The LLM model to use.
        prompt_kwargs: Keyword arguments for `prepare_llm_only_prompts` describing
            the column roles and schema (exposure, outcome, x0, x1, yt, mediators, confounders, dataset_semantic_schema).
        effort: The reasoning effort level ("low", "medium", or "high").

    Returns:
        An LLMReportResult containing the generated text, LaTeX, and usage information.
    """
    prompt_kwargs = prompt_kwargs or {}
    _validate_prompt_kwargs(prompt_kwargs)

    system_prompt, user_prompt = prepare_prompts(**prompt_kwargs)

    resp = client.responses.parse(
        model=model,
        reasoning={"effort": effort},
        instructions=system_prompt,
        text_format=FairnessReport,
        tools=[
            {
                "type": "code_interpreter",
                "container": {"type": "auto", "file_ids": [file_id]},
            },
        ],
        input=[
            {
                "role": "user",
                "content": [
                    {"type": "input_text", "text": user_prompt},
                ],
            }
        ],
    )

    return LLMReportResult(
        model=model,
        effort=effort,
        text=resp.output_parsed.text,
        latex=resp.output_parsed.latex,
        usage=resp.usage,
    )


def generate_report_from_dataset(
    data_path: str | Path | pd.DataFrame,
    client: Any,
    model: str = "gpt-5.4-nano",
    effort: str = "high",
    prompt_kwargs: dict[str, Any] | None = None,
) -> LLMReportResult:
    """
    Upload a local dataset file and generate a fairness decomposition report.

    Convenience wrapper around `generate_report_from_file_id` that handles the
    file upload, so callers only need a path and the column roles.

    Args:
        data_path: Path to the local dataset file (CSV or similar text table).
        client: The LLM client to use for upload and generation.
        model: The LLM model to use.
        prompt_kwargs: Keyword arguments for `prepare_llm_only_prompts` describing
            the column roles and schema (exposure, outcome, x0, x1, yt, mediators, confounders, dataset_semantic_schema).
            An example could be:
            ```
            {
                "CREDIT_HISTORY": {
                    "description": "The applicant's credit score.",
                    "states": {0: "bad", 1: "good"}
                }
            }
            ```
        effort: The reasoning effort level ("low", "medium", or "high").

    Returns:
        An LLMReportResult containing the generated text, LaTeX, and usage information.
    """
    if isinstance(data_path, pd.DataFrame):
        csv_bytes = data_path.to_csv(index=False).encode("utf-8")
        with io.BytesIO(csv_bytes) as f:
            f.seek(0)
            uploaded = client.files.create(file=f, purpose="assistants")
    else:
        with open(data_path, "rb") as f:
            uploaded = client.files.create(file=f, purpose="assistants")

    return generate_report_from_file_id(
        uploaded.id, client, model=model, prompt_kwargs=prompt_kwargs, effort=effort
    )
